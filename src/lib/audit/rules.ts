import type { FindingCategory, FindingType, Severity } from "./types";

/**
 * Catalogue of deterministic audit rules. This is the single source of truth
 * for rule titles, initial severities, detection methods and recommendations
 * (the Help page renders it directly).
 *
 * Thresholds such as title length are editorial GUIDANCE, not ranking factors.
 */

export interface SeverityContext {
  internal?: boolean;
  isStartPage?: boolean;
  count?: number;
}

export interface RuleDefinition {
  id: string;
  category: FindingCategory;
  type: FindingType;
  title: string;
  baseSeverity: Severity;
  /** Optional deterministic adjustment based on context. */
  severityFor?: (ctx: SeverityContext) => Severity;
  description: string;
  detectionMethod: string;
  recommendation: string;
}

