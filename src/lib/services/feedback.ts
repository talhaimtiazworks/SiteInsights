import "server-only";
import { randomUUID } from "node:crypto";
import { z } from "zod";
import type { AccountRepository, FeedbackSubmissionRow } from "../db/account-types";
import { userPrincipalId } from "../db/account-types";
import type { FeedbackMailer } from "../email/feedback-mailer";
import { renderFeedbackEmail } from "../email/feedback-template";

/**
 * Account-based feedback: counting, the one-time third-audit invitation, and
 * honest email delivery.
 *
 * Source of truth is ALWAYS the database (server side). Nothing here trusts
 * localStorage, cookies or client-side counters. The subset of the account
 * repository feedback needs is declared as FeedbackAccountStore so the logic
 * is unit-testable without a database connection.
 */

export const FEEDBACK_AUDIT_THRESHOLD = 3;
export const FEEDBACK_REMIND_AFTER_MS = 3 * 24 * 60 * 60 * 1000; // 72 h — a reminder, not a loop
export const FEEDBACK_MESSAGE_MIN = 20;
export const FEEDBACK_MESSAGE_MAX = 4000;
export const FEEDBACK_GOAL_MAX = 1000;

export const feedbackSubmitSchema = z
  .object({
    category: z.enum(["general", "bug", "feature", "other"]),
    rating: z.number().int().min(1).max(5).optional(),
    message: z.string().trim().min(FEEDBACK_MESSAGE_MIN).max(FEEDBACK_MESSAGE_MAX),
    goal: z.string().trim().min(1).max(FEEDBACK_GOAL_MAX).optional(),
    /** A page path like "/dashboard" the user was on — paths only, never full URLs. */
    pageUrl: z.string().regex(/^\/[A-Za-z0-9\-/]*$/).max(300).optional(),
    /** Gate-mandated idempotency: one UUID per logical submission, generated by the form on mount. */
    idempotencyKey: z.string().uuid(),
  })
  .strict();

export type FeedbackSubmitInput = z.infer<typeof feedbackSubmitSchema>;

export type FeedbackAccountStore = Pick<
  AccountRepository,
  | "countCompletedAuditsForUser"
  | "hasFeedbackSubmission"
  | "getFeedbackPrompt"
  | "ensureFeedbackPromptOffered"
  | "setFeedbackPromptResponse"
  | "insertFeedbackSubmission"
  | "updateFeedbackDelivery" | "listUndeliveredFeedback"
>;

export interface FeedbackPromptState {
  /** Successful terminal audits this account owns (completed | completed_with_warnings). */
  completedAudits: number;
  threshold: number;
  submittedAlready: boolean;
  /** True = render the invitation modal now. */
  show: boolean;
  promptState: "not_eligible" | "offered" | "remind_wait" | "remind_due" | "dismissed" | "submitted";
}

/**
 * Whether the invitation shows right now. Creating the invitation row is
 * INSERT ... ON CONFLICT DO NOTHING, so two audit completions finishing
 * concurrently in the same account still yield exactly one invitation.
 */
export async function getFeedbackPromptState(store: FeedbackAccountStore, userId: string, now: Date = new Date()): Promise<FeedbackPromptState> {
  const [completedAudits, submittedAlready] = await Promise.all([store.countCompletedAuditsForUser(userId), store.hasFeedbackSubmission(userId)]);
  if (submittedAlready) return { completedAudits, threshold: FEEDBACK_AUDIT_THRESHOLD, submittedAlready, show: false, promptState: "submitted" };
  if (completedAudits < FEEDBACK_AUDIT_THRESHOLD) return { completedAudits, threshold: FEEDBACK_AUDIT_THRESHOLD, submittedAlready, show: false, promptState: "not_eligible" };
  const prompt = await store.ensureFeedbackPromptOffered(userId);
  if (prompt.state === "dismissed") return { completedAudits, threshold: FEEDBACK_AUDIT_THRESHOLD, submittedAlready, show: false, promptState: "dismissed" };
  if (prompt.state === "remind_later") {
    const due = prompt.remindAfter !== null && new Date(prompt.remindAfter).getTime() <= now.getTime();
    return { completedAudits, threshold: FEEDBACK_AUDIT_THRESHOLD, submittedAlready, show: due, promptState: due ? "remind_due" : "remind_wait" };
  }
  return { completedAudits, threshold: FEEDBACK_AUDIT_THRESHOLD, submittedAlready, show: true, promptState: "offered" };
}

export async function respondToFeedbackInvite(
  store: FeedbackAccountStore,
  userId: string,
  action: "remind_later" | "dismiss",
): Promise<{ ok: true; state: FeedbackPromptState["promptState"] } | { ok: false; reason: "not_eligible" }> {
  const current = await getFeedbackPromptState(store, userId);
  // Response only meaningful while an invitation logically exists; dismissing or
  // snoozing nothing must not plant state (nor give any signal about other accounts).
  if (current.promptState === "not_eligible" || current.promptState === "submitted") return { ok: false, reason: "not_eligible" };
  if (action === "dismiss") {
    await store.setFeedbackPromptResponse(userId, { state: "dismissed", remindAfter: null });
    return { ok: true, state: "dismissed" };
  }
  await store.setFeedbackPromptResponse(userId, { state: "remind_later", remindAfter: new Date(Date.now() + FEEDBACK_REMIND_AFTER_MS) });
  return { ok: true, state: "remind_wait" };
}

export type SubmitFeedbackOutcome =
  | { kind: "delivered"; submissionId: string }
  | { kind: "already_recorded"; submissionId: string }
  | { kind: "email_not_configured"; submissionId: string }
  | { kind: "delivery_failed"; submissionId: string; retryable: boolean };

/**
 * Persist first, then deliver — never the other way round.
 *  - insert is idempotent on (userId, idempotencyKey): a double-click/retry with
 *    the same key reuses the row;
 *  - success is reported only when the provider accepted the message;
 *  - rows whose send outcome is uncertain (timeout after DATA et al.) are NEVER
 *    re-sent — that is how duplicate operator emails happen;
 *  - provider failures leave the row with delivery_status updates intact, so no
 *    feedback is silently lost.
 */
export async function submitFeedback(params: {
  store: FeedbackAccountStore;
  mailer: FeedbackMailer | null;
  userId: string;
  accountEmail: string | null;
  input: FeedbackSubmitInput;
  newId?: () => string;
}): Promise<SubmitFeedbackOutcome> {
  const { store, mailer, userId, accountEmail, input } = params;
  const { submission, created } = await store.insertFeedbackSubmission({
    id: (params.newId ?? randomUUID)(),
    userId,
    principalId: userPrincipalId(userId),
    accountEmail,
    category: input.category,
    rating: input.rating ?? null,
    message: input.message,
    goal: input.goal ?? null,
    pageUrl: input.pageUrl ?? null,
    idempotencyKey: input.idempotencyKey,
  });

  const alreadySettled = submission.deliveryStatus === "accepted" || submission.outcomeUncertain;
  if (!created && alreadySettled) return { kind: "already_recorded", submissionId: submission.id };

  if (!mailer) {
    await store.updateFeedbackDelivery(userId, submission.id, { deliveryStatus: "failed", deliveryErrorCode: "email_not_configured" });
    return { kind: "email_not_configured", submissionId: submission.id };
  }

  return deliverSubmission(store, mailer, { userId, accountEmail, submission });
}

type DeliverOutcome =
  | Extract<SubmitFeedbackOutcome, { kind: "delivered" }>
  | Extract<SubmitFeedbackOutcome, { kind: "delivery_failed" }>;

/** Attempt delivery for an existing persisted row and record the honest outcome. */
async function deliverSubmission(
  store: FeedbackAccountStore,
  mailer: FeedbackMailer,
  ctx: { userId: string; accountEmail: string | null; submission: FeedbackSubmissionRow },
): Promise<DeliverOutcome> {
  const { userId, accountEmail, submission } = ctx;
  const content = renderFeedbackEmail({
    submissionId: submission.id,
    category: submission.category,
    rating: submission.rating,
    message: submission.message,
    goal: submission.goal,
    pageUrl: submission.pageUrl,
    accountEmail,
    accountUserId: userId,
    submittedAt: submission.createdAt,
  });
  const result = await mailer.send({ subject: content.subject, text: content.text, html: content.html, replyTo: accountEmail });
  if (result.accepted) {
    await store.updateFeedbackDelivery(userId, submission.id, { deliveryStatus: "accepted", deliveryErrorCode: null, providerMessageId: result.providerMessageId });
    return { kind: "delivered", submissionId: submission.id };
  }
  await store.updateFeedbackDelivery(userId, submission.id, {
    deliveryStatus: "failed",
    deliveryErrorCode: result.code,
    outcomeUncertain: result.uncertain || undefined,
  });
  return { kind: "delivery_failed", submissionId: submission.id, retryable: !result.uncertain };
}

export type RetryFeedbackOutcome =
  | { kind: "email_not_configured"; pending: number }
  | { kind: "retried"; attempted: number; delivered: number; stillFailed: number; submissionIds: string[] };

/**
 * Re-attempt delivery for this account's saved-but-undelivered feedback WITHOUT
 * re-submitting anything. Idempotent by construction: the repository only ever
 * returns rows with delivery_status='failed' AND outcome_uncertain=false, so
 * already-delivered feedback and uncertain-outcome rows can never be emailed twice.
 * Sequential, bounded (≤50/call) to stay inside provider timeouts.
 */
export async function retryFeedbackDeliveries(params: {
  store: FeedbackAccountStore;
  mailer: FeedbackMailer | null;
  userId: string;
  accountEmail: string | null;
}): Promise<RetryFeedbackOutcome> {
  const { store, mailer, userId, accountEmail } = params;
  const pending = await store.listUndeliveredFeedback(userId, 50);
  if (pending.length === 0) return { kind: "retried", attempted: 0, delivered: 0, stillFailed: 0, submissionIds: [] };
  if (!mailer) return { kind: "email_not_configured", pending: pending.length };
  let delivered = 0;
  let stillFailed = 0;
  const submissionIds: string[] = [];
  for (const submission of pending) {
    const out = await deliverSubmission(store, mailer, { userId, accountEmail, submission });
    submissionIds.push(submission.id);
    if (out.kind === "delivered") delivered++;
    else stillFailed++;
  }
  return { kind: "retried", attempted: pending.length, delivered, stillFailed, submissionIds };
}
